"""Tabulate Experiment 1 students against the DKD, RLD and LoCa distillation baselines.

Reads a matrix output root (the directory holding matrix_summary.json) and renders one
Markdown table per metric. Every row is a study that produced a repaired teacher; every
cell is the test-set mean ± sample standard deviation over that study's student seeds.
The two KD columns come from the study's own student evaluation; a baseline column fills
in once `python -m kd distillation-baselines` has written that method's comparison.json.
Nothing is trained or modified.

    python scripts/baseline_comparison_table.py --matrix runs/experiment1-multidataset \
        --output docs/distillation-baselines-results.md
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

REFERENCES = {"kd_original": "baseline", "kd_repaired": "candidate"}
BASELINES = ("dkd", "rld", "loca")
COLUMNS = {"kd_original": "KD, original teacher", "kd_repaired": "KD, repaired teacher",
           "dkd": "DKD", "rld": "RLD", "loca": "LoCa"}
METRICS = {"accuracy": "Test accuracy (%)",
           "target_macro_recall": "Target-class macro recall (%)"}
DATASETS = {"cifar10": "CIFAR-10", "cifar100": "CIFAR-100", "cinic10": "CINIC-10",
            "svhn": "SVHN", "gtsrb": "GTSRB", "fashionmnist": "FashionMNIST",
            "pathmnist": "PathMNIST", "bloodmnist": "BloodMNIST", "dermamnist": "DermaMNIST",
            "organamnist": "OrganAMNIST", "caltech101": "Caltech101", "eurosat": "EuroSAT",
            "stl10": "STL-10"}
PROFILES = {"balanced": "Balanced", "lt-if10": "IF10", "lt-if50": "IF50", "lt-if100": "IF100"}


def _read(path: Path) -> dict:
    return json.loads(path.read_text())


def _study_cells(matrix: Path, job: dict) -> dict:
    """Per-seed metric values for every column of one study, or a pending status."""
    profile = matrix / job["dataset"] / job["profile"]
    evaluation = profile / "studies" / "confirmatory" / "student_evaluation"
    seeds = sorted(evaluation.glob("seed*"), key=lambda path: int(path.name[4:]))
    cells = {}
    for column, variant in REFERENCES.items():
        runs = [_read(seed / variant / "metrics.json") for seed in seeds]
        cells[column] = {metric: [run[metric] for run in runs] for metric in METRICS}
    for method in BASELINES:
        output = profile / "baselines" / "distillation" / method
        comparison = output / "comparison.json"
        if comparison.is_file() and _read(comparison).get("status") == "complete":
            rows = _read(comparison)["seeds"]
            cells[method] = {metric: [row["metrics"][metric] for row in rows] for metric in METRICS}
        else:
            trained = len(list(output.glob(f"{method}_*/completion.json")))
            cells[method] = f"training {trained}/{len(seeds)}" if trained else "pending"
    return cells


def _format(values: list[float]) -> str:
    spread = statistics.stdev(values) if len(values) > 1 else 0.0
    return f"{100 * statistics.mean(values):.2f} ± {100 * spread:.2f}"


def render(matrix: Path) -> str:
    summary = _read(matrix / "matrix_summary.json")
    jobs = [job for job in summary["jobs"] if job["status"] == "complete"]
    order = {name: index for index, name in enumerate(PROFILES)}
    jobs.sort(key=lambda job: (DATASETS.get(job["dataset"], job["dataset"]).lower(),
                             order[job["profile"]]))
    studies = [(job, _study_cells(matrix, job)) for job in jobs]
    finished = {method: sum(isinstance(cells[method], dict) for _, cells in studies)
                for method in BASELINES}

    lines = [
        "# Experiment 1 students against distillation baselines", "",
        f"Generated by `scripts/baseline_comparison_table.py` from `{matrix.name}` "
        f"({summary['job_count']} planned studies). Each row is one of the "
        f"{len(jobs)} studies that selected a repaired teacher; the other "
        f"{summary['job_count'] - len(jobs)} produced no repair and have nothing to compare.", "",
        "Every cell is test-set mean ± sample standard deviation over the study's three student "
        "seeds (42, 43, 44), in percent. All five students of a seed share the student "
        "architecture, initial weights, data, splits, schedule and checkpoint rule; only the "
        "teacher (original or repaired) or the distillation loss differs. **Transfer** marks "
        "the study's pre-registered success rule (mean target-recall gain ≥ 1 pp, at least two "
        "positive seeds, accuracy guardrail). Bold marks the best mean in a fully reported row.", "",
        "Baseline progress: " + ", ".join(f"{COLUMNS[method]} {finished[method]}/{len(jobs)}"
                                         for method in BASELINES) + ".", "",
    ]
    for metric, title in METRICS.items():
        lines += [f"## {title}", "",
                  "| Dataset | Profile | Transfer | " + " | ".join(COLUMNS.values()) + " |",
                  "|---|---|:-:|" + "---:|" * len(COLUMNS)]
        for job, cells in studies:
            means = {column: statistics.mean(cell[metric]) for column, cell in cells.items()
                     if isinstance(cell, dict)}
            best = max(means, key=means.get) if len(means) == len(COLUMNS) else None
            row = []
            for column in COLUMNS:
                cell = cells[column]
                text = _format(cell[metric]) if isinstance(cell, dict) else cell
                row.append(f"**{text}**" if column == best else text)
            lines.append(f"| {DATASETS.get(job['dataset'], job['dataset'])} | "
                         f"{PROFILES[job['profile']]} | {'✓' if job.get('success') else ''} | "
                         + " | ".join(row) + " |")
        overall = []
        for column in COLUMNS:
            values = [statistics.mean(cells[column][metric]) for _, cells in studies
                      if isinstance(cells[column], dict)]
            overall.append(f"{100 * statistics.mean(values):.2f}" if len(values) == len(studies)
                           else f"{len(values)}/{len(studies)} studies")
        lines += [f"| **Mean over studies** | | | " + " | ".join(overall) + " |", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--matrix", required=True, type=Path,
                        help="Matrix output root containing matrix_summary.json")
    parser.add_argument("--output", type=Path, help="Write Markdown here instead of stdout")
    args = parser.parse_args()
    text = render(args.matrix.resolve())
    if args.output:
        args.output.write_text(text)
    else:
        print(text)


if __name__ == "__main__":
    main()
