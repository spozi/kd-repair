"""Section 5 numbers for the 52-run Experiment 1 matrix.

Reads matrix_summary.json and each completed study's comparison.json, and prints Markdown
tables: where the protocol stopped, what the repair did to the teacher, and how much of it
reached the student. Study-level tests treat each completed study as one unit (the mean over
its three seeds). Nothing is trained or modified.

    python scripts/experiment1_results.py --matrix runs/experiment1-multidataset
"""

from __future__ import annotations

import argparse
import collections
import json
import statistics
from pathlib import Path

from scipy.stats import spearmanr, wilcoxon

from baseline_comparison_table import DATASETS, PROFILES

STOPS = {"Too few channels passed the configured localization guardrails.": "causal localization",
         "No repaired teacher strictly improved validation target recall within the 0.5-point "
         "accuracy guardrail.": "development selection"}


def _pp(value: float) -> str:
    return f"{100 * value:+.2f}"


def _p(value: float) -> str:
    return "<0.001" if value < 0.001 else f"{value:.3f}"


def load(matrix: Path) -> tuple[list[dict], list[dict]]:
    jobs = json.loads((matrix / "matrix_summary.json").read_text())["jobs"]
    studies = []
    for job in jobs:
        if job["status"] != "complete":
            continue
        comparison = json.loads((matrix / job["dataset"] / job["profile"] / "studies"
                                 / "confirmatory" / "comparison.json").read_text())
        teacher = comparison["teacher"]
        studies.append({
            "job": job, "selected": comparison["teacher_selection"]["selected"],
            "teacher_accuracy": teacher["candidate"]["accuracy"] - teacher["baseline"]["accuracy"],
            "teacher_recall": (teacher["candidate"]["target_macro_recall"]
                               - teacher["baseline"]["target_macro_recall"]),
            "teacher_mcnemar": teacher["accuracy"]["mcnemar_exact_two_sided_p"],
            "student_accuracy": comparison["aggregate"]["accuracy_delta"]["mean"],
            "student_recall": comparison["aggregate"]["target_recall_delta"]["mean"],
            "seed_recall": comparison["aggregate"]["target_recall_delta"]["values"],
            "passed": comparison["success"]["passed"],
        })
    return jobs, studies


def render(jobs: list[dict], studies: list[dict]) -> str:
    lines = ["# Experiment 1: Section 5 numbers", "",
             "Generated by `scripts/experiment1_results.py`. Differences are repaired minus "
             "original, in percentage points, on each study's sealed test split.", ""]

    stops = collections.Counter(STOPS.get(job.get("reason"), job["status"]) for job in jobs
                                if job["status"] != "complete")
    lines += ["## Where the protocol stopped", "",
              "| Profile | Runs | Repaired teacher selected | Stopped at causal localization | "
              "Stopped at development selection | Transfer rule passed |",
              "|---|---:|---:|---:|---:|---:|"]
    for profile, label in [*PROFILES.items(), (None, "**All**")]:
        group = [job for job in jobs if profile is None or job["profile"] == profile]
        stop = collections.Counter(STOPS.get(job.get("reason")) for job in group
                                   if job["status"] != "complete")
        passed = sum(study["passed"] for study in studies
                     if profile is None or study["job"]["profile"] == profile)
        selected = sum(job["status"] == "complete" for job in group)
        lines.append(f"| {label} | {len(group)} | {selected} | {stop['causal localization']} | "
                     f"{stop['development selection']} | {passed} |")
    lines += ["", f"Stops by stage over all runs: {dict(stops)}.", ""]

    lines += ["## Datasets", "", "| Dataset | Selected (of 4) | Localization stops | Selection stops "
              "| Transfer passed |", "|---|---:|---:|---:|---:|"]
    for dataset in sorted({job["dataset"] for job in jobs}, key=lambda d: DATASETS.get(d, d).lower()):
        group = [job for job in jobs if job["dataset"] == dataset]
        stop = collections.Counter(STOPS.get(job.get("reason")) for job in group
                                   if job["status"] != "complete")
        passed = sum(study["passed"] for study in studies if study["job"]["dataset"] == dataset)
        lines.append(f"| {DATASETS.get(dataset, dataset)} | {sum(job['status'] == 'complete' for job in group)} | "
                     f"{stop['causal localization']} | {stop['development selection']} | {passed} |")

    budgets = collections.Counter(study["selected"]["budget"] for study in studies)
    rates = collections.Counter(study["selected"]["learning_rate"] for study in studies)
    lines += ["", f"Selected channel budgets: {dict(sorted(budgets.items()))}; "
                  f"learning rates: {dict(sorted(rates.items()))}.", ""]

    n = len(studies)
    tailed = [study for study in studies if study["job"]["profile"] != "balanced"]
    lines += ["## Teacher and student effects of the repair", "",
              "| Quantity | Mean | Median | Positive | Wilcoxon p |", "|---|---:|---:|---:|---:|"]
    for key, label in [("teacher_accuracy", "Teacher accuracy"), ("teacher_recall", "Teacher target recall"),
                       ("student_accuracy", "Student accuracy (mean of 3 seeds)"),
                       ("student_recall", "Student target recall (mean of 3 seeds)")]:
        values = [study[key] for study in studies]
        nonzero = [value for value in values if value]
        lines.append(f"| {label} | {_pp(statistics.mean(values))} | {_pp(statistics.median(values))} | "
                     f"{sum(value > 0 for value in values)}/{n} | {_p(wilcoxon(nonzero).pvalue)} |")
    significant = sum(study["teacher_mcnemar"] < 0.05 and study["teacher_accuracy"] > 0 for study in studies)
    lines += ["", f"Teachers with a significant exact McNemar accuracy gain (p < 0.05, unadjusted): "
                  f"{significant}/{n}.", ""]

    lines += ["## Does the teacher's gain predict the student's?", "",
              "| Studies | Pair | Spearman ρ | p |", "|---|---|---:|---:|"]
    for group, label in [(studies, f"All {n}"), (tailed, f"Long-tailed {len(tailed)}")]:
        for left, right, name in [("teacher_recall", "student_recall", "target recall"),
                                  ("teacher_accuracy", "student_accuracy", "accuracy")]:
            rho, p = spearmanr([s[left] for s in group], [s[right] for s in group])
            lines.append(f"| {label} | Teacher vs student {name} | {rho:+.2f} | {_p(p)} |")
    lines += ["", f"Long-tailed studies whose student target recall rose on average: "
                  f"{sum(s['student_recall'] > 0 for s in tailed)}/{len(tailed)}.", ""]

    lines += ["## Per study", "",
              "| Dataset | Profile | Budget | Teacher Δacc | Teacher Δrecall | Student Δacc | "
              "Student Δrecall | Positive seeds | Transfer |",
              "|---|---|---:|---:|---:|---:|---:|---:|:-:|"]
    order = {name: index for index, name in enumerate(PROFILES)}
    for study in sorted(studies, key=lambda s: (DATASETS.get(s["job"]["dataset"], "").lower(),
                                                order[s["job"]["profile"]])):
        lines.append(
            f"| {DATASETS.get(study['job']['dataset'], study['job']['dataset'])} | "
            f"{PROFILES[study['job']['profile']]} | {study['selected']['budget']} | "
            f"{_pp(study['teacher_accuracy'])} | {_pp(study['teacher_recall'])} | "
            f"{_pp(study['student_accuracy'])} | {_pp(study['student_recall'])} | "
            f"{sum(value > 0 for value in study['seed_recall'])}/3 | {'✓' if study['passed'] else ''} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--matrix", type=Path, default=Path("runs/experiment1-multidataset"))
    parser.add_argument("--output", type=Path, help="Write Markdown here instead of stdout")
    args = parser.parse_args()
    text = render(*load(args.matrix.resolve()))
    if args.output:
        args.output.write_text(text)
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
